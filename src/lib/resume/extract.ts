/** Locate every `stream … endstream` payload. */
function* findStreams(buf: Buffer): Generator<Buffer> {
  const hay = buf.toString("latin1");
  let i = 0;
  let found = 0;
  while (found < 500) {
    const start = hay.indexOf("stream", i);
    if (start === -1) return;
    // Skip the EOL after the keyword — CRLF or LF, per the spec.
    let s = start + 6;
    if (hay[s] === "\r") s++;
    if (hay[s] === "\n") s++;
    const end = hay.indexOf("endstream", s);
    if (end === -1) return;
    yield buf.subarray(s, end);
    i = end + 9;
    found++;
  }
}

/** inflateRawSync wants no zlib header; most PDF streams carry one. */
function stripZlibHeader(b: Buffer): Buffer {
  if (b.length > 2 && (b[0] & 0x0f) === 8 && ((b[0] << 8) | b[1]) % 31 === 0) {
    return b.subarray(2);
  }
  return b;
}

/**
 * Read the text-showing operators out of an inflated content stream.
 *
 * `(…) Tj`, `(…) '`, `(…) "` show a string. `[…] TJ` shows an array of strings
 * interleaved with kerning numbers, which are discarded. `TD`, `Td`, `T*` and
 * `ET` are line/paragraph boundaries and become newlines — without them the
 * whole resume collapses to one line and section detection fails.
 */
function readTextOperators(s: string): string {
  const out: string[] = [];
  const re = /\((?:\\.|[^\\()])*\)|\[(?:[^\]\\]|\\.)*\]|\bT[Dd*]\b|\bET\b|\bTJ\b|\bTj\b|'|"/g;
  let pending: string[] = [];

  for (const m of s.matchAll(re)) {
    const tok = m[0];
    if (tok.startsWith("(")) {
      pending.push(decodePdfString(tok.slice(1, -1)));
    } else if (tok.startsWith("[")) {
      for (const lit of tok.matchAll(/\((?:\\.|[^\\()])*\)/g)) {
        pending.push(decodePdfString(lit[0].slice(1, -1)));
      }
    } else if (tok === "TJ" || tok === "Tj" || tok === "'" || tok === '"') {
      if (pending.length) {
        out.push(pending.join(""));
        pending = [];
      }
    } else {
      // Positioning or end-of-text: a line break.
      if (pending.length) {
        out.push(pending.join(""));
        pending = [];
      }
      out.push("\n");
    }
  }
  if (pending.length) out.push(pending.join(""));
  return out.join("");
}

function decodePdfString(s: string): string {
  return s
    .replace(/\\n/g, "\n")
    .replace(/\\r/g, "\r")
    .replace(/\\t/g, "\t")
    .replace(/\\b/g, "\b")
    .replace(/\\f/g, "\f")
    .replace(/\\([0-7]{1,3})/g, (_, o) => String.fromCharCode(parseInt(o, 8)))
    .replace(/\\(.)/g, "$1");
}

type ZipEntry = { data: Buffer; method: number };

/**
 * Find one entry in a ZIP by walking local file headers.
 *
 * Bounded to 200 entries: a DOCX has a handful, and an archive with thousands
 * is either malicious or not a resume. This is the zip-bomb guard.
 */
function findZipEntry(buf: Buffer, name: string): ZipEntry | null {
  let off = 0;
  let seen = 0;
  while (off + 30 <= buf.length && seen < 200) {
    if (buf.readUInt32LE(off) !== 0x04034b50) break;
    const method = buf.readUInt16LE(off + 8);
    const compSize = buf.readUInt32LE(off + 18);
    const nameLen = buf.readUInt16LE(off + 26);
    const extraLen = buf.readUInt16LE(off + 28);
    const nameStart = off + 30;
    const entryName = buf.subarray(nameStart, nameStart + nameLen).toString("utf8");
    const dataStart = nameStart + nameLen + extraLen;

    // A streamed zip writes sizes to a trailing descriptor, so compSize is 0
    // here. Those are rare for DOCX; skip rather than guess at the length.
    if (compSize === 0 && entryName !== name) break;

    if (entryName === name) {
      const data = buf.subarray(dataStart, dataStart + compSize);
      // A single entry inflating to >64MB is a decompression bomb, not a resume.
      if (compSize > 32 * 1024 * 1024) return null;
      return { data, method };
    }
    off = dataStart + compSize;
    seen++;
  }
  return null;
}

/** Collapse whitespace without destroying the line structure. */
function normalise(s: string): string {
  return s
    .replace(/\r\n?/g, "\n")
    .replace(/[ \t ]+/g, " ")
    .replace(/ *\n */g, "\n")
    .replace(/\n{3,}/g, "\n\n")
    // Strip control characters, which appear when a font encoding is unusual.
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g, "")
    .trim();
}
